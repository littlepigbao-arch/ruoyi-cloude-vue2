'use strict'
// C3-FE-02 import API client regression (offline). Drives the REAL axios instance that
// src/api/ai/import.js builds, through the real transform chain, into a recording offline
// adapter (no backend, no network). Guards the two production-entry contracts the Codex
// FE-02 re-review flagged:
//   F1 (P1) - src/utils/request.js:14 sets axios.defaults.headers['Content-Type'] =
//             'application/json;charset=utf-8' before api modules are evaluated and
//             axios.create() snapshots it. Installed axios 0.30.3 deliberately converts
//             FormData carrying that header into a JSON string (defaults/index.js:
//             JSON.stringify(formDataToJSON(data))), replacing the file bytes with
//             {"file":{},...}. The client must delete the inherited header for FormData
//             payloads and hand the untouched FormData to the adapter (multipart/boundary
//             is generated by the runtime itself).
//   F2 (P1) - the default transformResponse JSON.parses the wire body, materializing every
//             number token as a JS Number and silently rounding decimals past 17
//             significant digits. The client must keep lossy literals (the 29-digit
//             0.12345678901234567890123456789) as exact strings while every Number-
//             carriable value (123, -45.75, 45838.99998842592) stays a JS Number.
// Codex 2nd-round re-review gaps, same real axios/transform chain:
//   GAP1 (P1) - the old <=15-significant-digit fast path let out-of-range tokens materialize
//               as Infinity (1e400), 0 (1E-400) or a rounded subnormal (4e-324 -> 5e-324; even
//               15 significant digits round near 1e-310). The guard is now an exact decimal-
//               value equivalence (BigInt cross-multiplication), so value-equal spellings
//               (1e2 == 100) stay Numbers while every literal a Number would alter keeps its
//               exact text as a string.
//   GAP2 (P2) - the old '\u0000RAW\u0000' string-prefix sentinel corrupted genuine payload
//               strings wearing that prefix (POI shared-string _x0000_RAW_x0000_... decode
//               product). Restore now unwraps only a single-key object keyed by a per-parse
//               nonce; strings are returned verbatim, character for character.
// Plus the two stable semantics around them: duplicate requestId posts are never suppressed
// client-side (idempotency is the server-side requestId contract) and the code!==200
// business error shape (error.code / error.definitive).
// The global default mutations below replicate the app-boot order (request.js evaluates
// before api modules) and MUST run before import.js is loaded, so axios.create() snapshots
// the poisoned JSON header plus the offline adapter exactly as production would.
const assert = require('assert'), fs = require('fs'), path = require('path'), { createRequire } = require('module')
const root = path.resolve(__dirname, '../..'), rf = createRequire(path.join(root, 'package.json')), babel = rf('@babel/core'), cache = new Map()
function load(file) {
  if (cache.has(file)) return cache.get(file).exports
  const module = { exports: {} }
  cache.set(file, module)
  const source = babel.transformSync(fs.readFileSync(file, 'utf8'), { filename: file, babelrc: false, configFile: false, plugins: [rf.resolve('@babel/plugin-transform-modules-commonjs')] }).code
  const localRequire = name => name === '@/utils/auth' ? { getToken: () => 'c3-test-token' }
    : name.startsWith('.') ? load(path.resolve(path.dirname(file), name + '.js')) : rf(name)
  new Function('require', 'module', 'exports', source)(localRequire, module, module.exports)
  return module.exports
}

// App-boot replication (request.js:14): global JSON Content-Type that axios.create() inherits.
const axios = rf('axios')
axios.defaults.headers['Content-Type'] = 'application/json;charset=utf-8'

// Recording offline adapter: every dispatch lands in `calls`; response bodies come from a
// per-case FIFO so each test states exactly what the wire would answer.
const calls = [], bodies = []
axios.defaults.adapter = config => {
  calls.push({ method: config.method, url: config.url, data: config.data, headers: config.headers })
  return Promise.resolve({ data: bodies.shift(), status: 200, statusText: 'OK', headers: {}, config, request: {} })
}

let passed = 0, failed = 0
async function test(name, fn) { try { await fn(); passed++; console.log('PASS ' + name) } catch (e) { failed++; console.error('FAIL ' + name + ': ' + e.message) } }

;(async () => {
  // Red/green anchor: loads the production client AFTER the poisoned global defaults above.
  const api = load(path.join(root, 'src/api/ai/import.js'))

  const LITERAL = '0.12345678901234567890123456789'
  // Exact wire text of a bounded preview response: the RuoYi envelope importRequest unwraps
  // (code/msg/data), with the 29-digit literal as a RAW JSON number token inside data (as the
  // backend PRECISE_JSON lane emits it), alongside a plain number and a text cell.
  const PREVIEW_WIRE = '{"code":200,"msg":"ok","data":{"jobId":"job-1","sourceHash":"' + 'c'.repeat(64) + '","sheetCount":1,' +
    '"totalRowCount":1,"requestedRows":50,"returnedRows":1,"limited":true,"fullSourceCoverage":false,' +
    '"note":"预览仅返回有限行与元信息，不承诺覆盖全量源工作簿","sheets":[],"rows":[' +
    '{"sheetId":"sheet-0","sheetIndex":0,"rowIndex":0,"cells":{' +
    '"0":{"v":' + LITERAL + ',"t":2},' +
    '"1":{"v":123,"t":2},' +
    '"2":{"v":"001","t":1},' +
    // GAP1 counter-examples, emitted by the backend BigDecimal lane as raw JSON number tokens:
    '"4":{"v":1e400,"t":2},' +                 // overflow: naive Number() -> Infinity
    '"5":{"v":1E-400,"t":2},' +                // underflow: naive Number() -> 0
    '"6":{"v":4e-324,"t":2},' +                // subnormal: naive Number() -> 5e-324
    '"7":{"v":1.23456789012345e-310,"t":2},' + // 15 sig digits still round in the subnormal region
    '"8":{"v":1e2,"t":2},' +                   // value-equal to 100: must stay a Number
    // GAP2: genuine payload text wearing the legacy sentinel prefix. The \\u0000 pairs keep the
    // wire text JSON-escaped in this source; JSON.parse decodes them to real NUL chars at runtime.
    '"9":{"v":"\\u0000RAW\\u0000original-text","t":1}' +
    '}}]}}'
  const FILE_CONTENT = Buffer.from('PK\x03\x04 c3 upload fidelity bytes 高精度')
  const file = typeof File === 'function'
    ? new File([FILE_CONTENT], '高精度.xlsx', { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' })
    : Object.assign(new Blob([FILE_CONTENT], { type: 'application/octet-stream' }), { name: '高精度.xlsx' })

  await test('F1 upload fidelity: FormData reaches the adapter untouched, without the inherited JSON Content-Type', async () => {
    bodies.length = 0
    bodies.push('{"code":200,"msg":"ok","data":{"jobId":"j-keep"}}')
    await api.createImportJob(file, 'req-keep-1')
    const call = calls[calls.length - 1]
    assert.strictEqual(call.method, 'post')
    assert.strictEqual(call.url, '/ai/agent/import/jobs')
    const data = call.data
    assert.ok(data instanceof FormData, 'captured data must be a FormData instance (not a string), got: ' + typeof data + ' ' + String(data).slice(0, 80))
    assert.strictEqual(data.get('requestId'), 'req-keep-1')
    const sent = data.get('file')
    assert.ok(sent instanceof Blob, 'file part must survive as a Blob, got: ' + typeof sent)
    assert.strictEqual(sent.name, '高精度.xlsx', 'file name must survive the transform chain')
    assert.strictEqual(sent.size, FILE_CONTENT.length, 'file byte length must survive')
    assert.strictEqual(Buffer.from(await sent.arrayBuffer()).toString('utf8'), FILE_CONTENT.toString('utf8'), 'file bytes must be identical')
    const ct = call.headers['Content-Type']
    assert.ok(!ct || String(ct).indexOf('application/json') < 0, 'Content-Type must not be application/json, got: ' + ct)
  })

  await test('duplicate requestId is dispatched twice: idempotency stays server-side (no client suppression)', async () => {
    bodies.length = 0
    bodies.push('{"code":200,"msg":"ok","data":{"jobId":"j-dup-1"}}')
    bodies.push('{"code":200,"msg":"ok","data":{"jobId":"j-dup-2"}}')
    const before = calls.length
    await api.createImportJob(file, 'req-dup')
    await api.createImportJob(file, 'req-dup')
    // Reads the requestId off the captured payload in either shape (FormData post-fix, or the
    // JSON string the poisoned default transform produces pre-fix) so this case pins ONLY the
    // both-dispatches-reach-the-adapter semantics, independent of F1.
    const requestIdOf = d => typeof d.get === 'function' ? d.get('requestId') : JSON.parse(d).requestId
    const posts = calls.slice(before).filter(c => c.method === 'post' && c.url === '/ai/agent/import/jobs')
    assert.strictEqual(posts.length, 2, 'both posts must reach the adapter, got: ' + posts.length)
    assert.strictEqual(requestIdOf(posts[0].data), 'req-dup')
    assert.strictEqual(requestIdOf(posts[1].data), 'req-dup')
  })

  await test('F2 preview precision: 29-digit literal stays an exact string; 123 stays a number; "001" untouched', async () => {
    bodies.length = 0
    bodies.push(PREVIEW_WIRE)
    const preview = await api.previewImport('job-1', 'c'.repeat(64), 50)
    const cells = preview.rows[0].cells
    const v = cells['0'].v
    assert.strictEqual(typeof v, 'string', '29-digit literal must arrive as a string, got: ' + typeof v + ' (' + v + ')')
    assert.strictEqual(v.length, LITERAL.length, 'literal length must be preserved')
    for (let i = 0; i < LITERAL.length; i++) assert.strictEqual(v[i], LITERAL[i], 'char ' + i + ' of the literal drifted: ' + v)
    assert.strictEqual(v, LITERAL, 'every digit of the literal must survive')
    assert.strictEqual(typeof cells['1'].v, 'number', '123 must stay a JS Number')
    assert.strictEqual(cells['1'].v, 123)
    assert.strictEqual(cells['2'].v, '001')
    assert.strictEqual(typeof cells['2'].v, 'string', '"001" must stay text')
  })

  await test('Codex GAP1 counter-examples: out-of-range and subnormal literals keep their exact text; 1e2 stays Number 100', async () => {
    bodies.length = 0
    bodies.push(PREVIEW_WIRE)
    const preview = await api.previewImport('job-1', 'c'.repeat(64), 50)
    const cells = preview.rows[0].cells
    const got = key => (cells[key] === undefined ? '<missing>' : typeof cells[key].v + ':' + String(cells[key].v))
    const snapshot = JSON.stringify({
      '4(1e400)': got('4'), '5(1E-400)': got('5'), '6(4e-324)': got('6'),
      '7(1.23456789012345e-310)': got('7'), '8(1e2)': got('8')
    })
    assert.strictEqual(cells['4'].v, '1e400', '1e400 must stay the exact literal string (never Infinity), got: ' + got('4') + ' | all: ' + snapshot)
    assert.strictEqual(typeof cells['4'].v, 'string', '1e400 must arrive as a string, got: ' + got('4') + ' | all: ' + snapshot)
    assert.strictEqual(cells['5'].v, '1E-400', '1E-400 must keep its exact spelled text (not 0/number), got: ' + got('5') + ' | all: ' + snapshot)
    assert.strictEqual(cells['6'].v, '4e-324', '4e-324 must keep its exact text (not 5e-324), got: ' + got('6') + ' | all: ' + snapshot)
    const SUBNORMAL = '1.23456789012345e-310'
    assert.strictEqual(typeof cells['7'].v, 'string', '15-digit subnormal literal must arrive as a string, got: ' + got('7') + ' | all: ' + snapshot)
    assert.strictEqual(cells['7'].v.length, SUBNORMAL.length, 'subnormal literal length must be preserved, got: ' + got('7') + ' | all: ' + snapshot)
    for (let i = 0; i < SUBNORMAL.length; i++) assert.strictEqual(cells['7'].v[i], SUBNORMAL[i], 'char ' + i + ' of the subnormal literal drifted, got: ' + JSON.stringify(cells['7'].v) + ' | all: ' + snapshot)
    assert.strictEqual(cells['7'].v, SUBNORMAL, 'every char of the subnormal literal must survive, got: ' + got('7') + ' | all: ' + snapshot)
    assert.strictEqual(cells['8'].v, 100, '1e2 is value-equal to 100 and must stay a Number, got: ' + got('8') + ' | all: ' + snapshot)
    assert.strictEqual(typeof cells['8'].v, 'number', '1e2 must materialize as a JS Number, got: ' + got('8') + ' | all: ' + snapshot)
  })

  await test('Codex GAP2: a genuine payload string wearing the legacy sentinel prefix survives verbatim', async () => {
    bodies.length = 0
    bodies.push(PREVIEW_WIRE)
    const preview = await api.previewImport('job-1', 'c'.repeat(64), 50)
    const v = preview.rows[0].cells['9'].v
    const LEGACY = '\u0000RAW\u0000original-text'
    assert.strictEqual(typeof v, 'string', 'legacy-prefixed payload text must stay a string, got: ' + typeof v + ' ' + JSON.stringify(v))
    assert.strictEqual(v, LEGACY, 'string with real NULs must survive untouched (not stripped to "original-text"), got: ' + JSON.stringify(v))
    for (let i = 0; i < LEGACY.length; i++) assert.strictEqual(v[i], LEGACY[i], 'char ' + i + ' drifted, got: ' + JSON.stringify(v))
  })

  await test('business error semantics: code 409 rejects with error.code=409 and definitive=true', async () => {
    bodies.length = 0
    bodies.push('{"code":409,"msg":"IMPORT_DUPLICATE_REQUEST","data":{"kind":"row-limit","limit":1000,"observed":1001}}')
    await assert.rejects(
      api.previewImport('job-1', 'c'.repeat(64), 50),
      err => err.code === 409 && err.definitive === true && err.message === 'IMPORT_DUPLICATE_REQUEST'
    )
  })

  await test('success payload passes through as response.data', async () => {
    bodies.length = 0
    bodies.push('{"code":200,"msg":"ok","data":{"jobId":"j1"}}')
    const result = await api.getImportJob('j1')
    assert.deepStrictEqual(result, { jobId: 'j1' })
  })

  console.log(JSON.stringify({ passed, failed, scope: 'OFFLINE_REAL_AXIOS_TRANSFORM_CHAIN_NO_BACKEND_NO_NETWORK' }))
  process.exitCode = failed ? 1 : 0
})()
